# ============================================================
# 4. HELPER FUNCTION: Build full prompt for any LLM
# ============================================================

def build_sudanese_prompt(region: str = "khartoum", user_message: str = "", include_few_shot: bool = True) -> str:
    """
    Returns a complete prompt ready to send to any LLM.
    """
    region = region.lower().strip()
    if region not in REGION_PROMPTS:
        region = "khartoum"

    prompt_parts = [MASTER_SYSTEM_PROMPT, "", REGION_PROMPTS[region]]

    if include_few_shot and region in FEW_SHOT_EXAMPLES:
        prompt_parts.append("\n### أمثلة:")
        for ex in FEW_SHOT_EXAMPLES[region]:
            prompt_parts.append(f"المستخدم: {ex['user']}")
            prompt_parts.append(f"المساعد: {ex['assistant']}")
            prompt_parts.append("")

    if user_message:
        prompt_parts.append(f"المستخدم: {user_message}")
        prompt_parts.append("المساعد:")

    return "\n".join(prompt_parts)


